package cd.labyrinthe.connect;

import java.util.Collections;
import java.util.Map;
import java.util.Optional;
import java.util.OptionalLong;
import java.util.TreeMap;

/**
 * What the SDK read from a successful response, given to {@link
 * RequestOptions.Builder#onResponse(java.util.function.Consumer)}. Immutable.
 */
public final class ResponseInfo {

  private final int status;
  private final Map<String, String> headers;

  ResponseInfo(int status, Map<String, String> headers) {
    this.status = status;
    this.headers = Collections.unmodifiableMap(new TreeMap<>(headers));
  }

  /**
   * HTTP status.
   *
   * @return e.g. 200, 201, 202
   */
  public int status() {
    return status;
  }

  /**
   * Request identifier ({@code X-Request-Id}): yours when you passed {@link
   * RequestOptions#requestId(String)}, otherwise generated by the API. Give it to the support.
   *
   * @return the identifier, if the API sent one
   */
  public Optional<String> requestId() {
    return Optional.ofNullable(headers.get("x-request-id"));
  }

  /**
   * Major API version that served the response ({@code X-Api-Version}).
   *
   * @return e.g. {@code "1"}, if the API sent it
   */
  public Optional<String> apiVersion() {
    return Optional.ofNullable(headers.get("x-api-version"));
  }

  /**
   * Whether the response is the replay of an earlier request with the same {@code Idempotency-Key}
   * ({@code Idempotent-Replayed: true}): nothing was sent or billed again.
   *
   * @return true for a replay
   */
  public boolean replayed() {
    return "true".equals(headers.get("idempotent-replayed"));
  }

  /**
   * Requests allowed per minute ({@code X-RateLimit-Limit}).
   *
   * @return the limit, if sent
   */
  public OptionalLong rateLimitLimit() {
    return number("x-ratelimit-limit");
  }

  /**
   * Requests left in the current minute ({@code X-RateLimit-Remaining}).
   *
   * @return the remaining requests, if sent
   */
  public OptionalLong rateLimitRemaining() {
    return number("x-ratelimit-remaining");
  }

  /**
   * Every response header, with lower-case names (first value only).
   *
   * @return unmodifiable headers
   */
  public Map<String, String> headers() {
    return headers;
  }

  private OptionalLong number(String name) {
    String value = headers.get(name);
    Long parsed = value == null ? null : parseOrNull(value.trim());
    return parsed == null ? OptionalLong.empty() : OptionalLong.of(parsed);
  }

  private static Long parseOrNull(String value) {
    try {
      return Long.parseLong(value);
    } catch (NumberFormatException e) {
      return null;
    }
  }

  @Override
  public String toString() {
    return "ResponseInfo(status="
        + status
        + ", requestId="
        + requestId().orElse(null)
        + ", apiVersion="
        + apiVersion().orElse(null)
        + ", replayed="
        + replayed()
        + ")";
  }
}
