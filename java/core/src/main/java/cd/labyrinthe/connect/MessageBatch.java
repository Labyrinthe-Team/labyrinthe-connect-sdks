package cd.labyrinthe.connect;

import java.util.Collections;
import java.util.Iterator;
import java.util.List;
import java.util.Objects;
import java.util.Optional;

/** Result of {@code sms().sendMany()}: one message per distinct recipient. Immutable. */
public final class MessageBatch implements Iterable<Message> {

  private final List<Message> messages;
  private final String idempotencyKey;
  private final boolean replayed;
  private final String requestId;

  MessageBatch(List<Message> messages, String idempotencyKey, boolean replayed, String requestId) {
    this.messages = Collections.unmodifiableList(List.copyOf(messages));
    this.idempotencyKey = Objects.requireNonNull(idempotencyKey, "idempotencyKey");
    this.replayed = replayed;
    this.requestId = requestId;
  }

  /**
   * The messages, one per distinct recipient (duplicates are merged by the API).
   *
   * @return unmodifiable list
   */
  public List<Message> messages() {
    return messages;
  }

  /**
   * The {@code Idempotency-Key} used for this send (yours, or the one generated by the SDK).
   *
   * @return the key
   */
  public String idempotencyKey() {
    return idempotencyKey;
  }

  /**
   * Whether the API replayed an earlier identical request: nothing was sent or billed again.
   *
   * @return true for a replay
   */
  public boolean replayed() {
    return replayed;
  }

  /**
   * Request identifier of the response ({@code X-Request-Id}), for the support. Not part of {@link
   * #equals(Object)}.
   *
   * @return the identifier, if the API sent one
   */
  public Optional<String> requestId() {
    return Optional.ofNullable(requestId);
  }

  /**
   * Number of messages.
   *
   * @return the size
   */
  public int size() {
    return messages.size();
  }

  @Override
  public Iterator<Message> iterator() {
    return messages.iterator();
  }

  @Override
  public boolean equals(Object other) {
    if (this == other) {
      return true;
    }
    if (!(other instanceof MessageBatch)) {
      return false;
    }
    MessageBatch that = (MessageBatch) other;
    return replayed == that.replayed
        && messages.equals(that.messages)
        && idempotencyKey.equals(that.idempotencyKey);
  }

  @Override
  public int hashCode() {
    return Objects.hash(messages, idempotencyKey, replayed);
  }

  @Override
  public String toString() {
    return "MessageBatch(size=" + messages.size() + ", replayed=" + replayed + ")";
  }
}
