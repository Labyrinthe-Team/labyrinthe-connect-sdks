package cd.labyrinthe.connect;

import java.time.Duration;
import java.time.Instant;
import java.util.Objects;
import java.util.Optional;

/**
 * Result of an OTP send. Immutable.
 *
 * <p>Store {@link #otpId()} server-side (session, cache…) and pass it to {@code otp().verify()}
 * with the code typed by the user. {@link #codeLength()} and {@link #codeType()} describe the input
 * field; {@link #resendAfterSeconds()} drives a "Resend the code" countdown.
 */
public final class OtpSendResult {

  private final String otpId;
  private final Instant expiresAt;
  private final int maxAttempts;
  private final int codeLength;
  private final OtpCodeType codeType;
  private final int resendAfterSeconds;
  private final String testCode;
  private final String idempotencyKey;
  private final boolean replayed;

  OtpSendResult(
      String otpId,
      Instant expiresAt,
      int maxAttempts,
      int codeLength,
      OtpCodeType codeType,
      int resendAfterSeconds,
      String testCode,
      String idempotencyKey,
      boolean replayed) {
    this.otpId = Objects.requireNonNull(otpId, "otpId");
    this.expiresAt = Objects.requireNonNull(expiresAt, "expiresAt");
    this.maxAttempts = maxAttempts;
    this.codeLength = codeLength;
    this.codeType = Objects.requireNonNull(codeType, "codeType");
    this.resendAfterSeconds = resendAfterSeconds;
    this.testCode = testCode;
    this.idempotencyKey = Objects.requireNonNull(idempotencyKey, "idempotencyKey");
    this.replayed = replayed;
  }

  /**
   * Identifier of this code, to pass to {@code otp().verify()}.
   *
   * @return the OTP id
   */
  public String otpId() {
    return otpId;
  }

  /**
   * Expiry time of the code.
   *
   * @return the expiry time
   */
  public Instant expiresAt() {
    return expiresAt;
  }

  /**
   * Number of verification attempts allowed.
   *
   * @return the attempts
   */
  public int maxAttempts() {
    return maxAttempts;
  }

  /**
   * Number of characters of the code (account's OTP settings, 4 to 8).
   *
   * @return the length, or {@code 0} when the API (older than 1.2.0) does not send it
   */
  public int codeLength() {
    return codeLength;
  }

  /**
   * Alphabet of the code: numeric keypad or text field.
   *
   * @return the type ({@link OtpCodeType#UNKNOWN} when absent or unknown)
   */
  public OtpCodeType codeType() {
    return codeType;
  }

  /**
   * Seconds before a new send to the same number is accepted while this code is not verified
   * (otherwise {@code OTP_RESEND_TOO_SOON}).
   *
   * @return the delay in seconds ({@code 0} when the API, older than 1.2.0, does not send it)
   */
  public int resendAfterSeconds() {
    return resendAfterSeconds;
  }

  /**
   * {@link #resendAfterSeconds()} as a duration.
   *
   * @return the delay
   */
  public Duration resendAfter() {
    return Duration.ofSeconds(resendAfterSeconds);
  }

  /**
   * The code, <b>only</b> with a test key ({@code lsk_test_…}).
   *
   * <p>Nothing is sent by SMS in test mode, so the API returns the code to let you test {@code
   * verify()}. Always empty with a live key. Never log it, never show it to end users. It is
   * excluded from {@link #toString()}, {@link #equals(Object)} and {@link #hashCode()}.
   *
   * @return the code in test mode, empty otherwise
   */
  public Optional<String> testCode() {
    return Optional.ofNullable(testCode);
  }

  /**
   * The {@code Idempotency-Key} used for this send (yours, or the one generated by the SDK). Reuse
   * it to retry the same send safely.
   *
   * @return the key
   */
  public String idempotencyKey() {
    return idempotencyKey;
  }

  /**
   * Whether the API replayed an earlier identical request (same {@code Idempotency-Key}): no new
   * SMS was sent or billed, the {@link #otpId()} is the original one.
   *
   * @return true for a replay
   */
  public boolean replayed() {
    return replayed;
  }

  @Override
  public boolean equals(Object other) {
    if (this == other) {
      return true;
    }
    if (!(other instanceof OtpSendResult)) {
      return false;
    }
    OtpSendResult that = (OtpSendResult) other;
    return maxAttempts == that.maxAttempts
        && codeLength == that.codeLength
        && resendAfterSeconds == that.resendAfterSeconds
        && replayed == that.replayed
        && codeType == that.codeType
        && otpId.equals(that.otpId)
        && expiresAt.equals(that.expiresAt)
        && idempotencyKey.equals(that.idempotencyKey);
  }

  @Override
  public int hashCode() {
    return Objects.hash(
        otpId,
        expiresAt,
        maxAttempts,
        codeLength,
        codeType,
        resendAfterSeconds,
        idempotencyKey,
        replayed);
  }

  /** The test code is never shown. */
  @Override
  public String toString() {
    return "OtpSendResult(otpId="
        + otpId
        + ", expiresAt="
        + expiresAt
        + ", maxAttempts="
        + maxAttempts
        + ", codeLength="
        + codeLength
        + ", codeType="
        + codeType
        + ", resendAfterSeconds="
        + resendAfterSeconds
        + ", replayed="
        + replayed
        + ", testCode="
        + (testCode == null ? "none" : "[redacted]")
        + ")";
  }
}
