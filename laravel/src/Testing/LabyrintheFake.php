<?php

declare(strict_types=1);

namespace Labyrinthe\Connect\Laravel\Testing;

use Illuminate\Contracts\Container\Container;
use Labyrinthe\Connect\Client;
use Labyrinthe\Connect\Laravel\LabyrintheManager;
use Labyrinthe\Connect\PhoneNumber;
use PHPUnit\Framework\Assert as PHPUnit;

/**
 * Returned by Labyrinthe::fake(). Records SMS and OTP instead of calling the
 * API, and offers assertions:
 *
 *     $fake = Labyrinthe::fake();
 *     $user->notify(new OrderShipped($order));
 *     Labyrinthe::assertSmsSentTo($user->phone, fn (SentSms $sms) => str_contains($sms->body, 'shipped'));
 *
 * The real SDK runs underneath (validation, normalisation, typed errors).
 */
class LabyrintheFake extends LabyrintheManager
{
    private readonly FakeApi $api;

    private readonly Client $fakeClient;

    private readonly string $countryCode;

    public function __construct(Container $container)
    {
        parent::__construct($container);

        $config = $container->make('config');
        $countryCode = $config->get('labyrinthe.default_country_code', PhoneNumber::DEFAULT_COUNTRY_CODE);
        $countryCode = \is_scalar($countryCode) && (string) $countryCode !== '' ? (string) $countryCode : PhoneNumber::DEFAULT_COUNTRY_CODE;
        $sender = $config->get('labyrinthe.sender');

        $this->countryCode = $countryCode;
        $this->api = new FakeApi($countryCode);
        $this->fakeClient = new Client(
            apiKey: 'lsk_test_fake',
            baseUrl: 'https://labyrinthe.fake/api/public/v1',
            maxRetries: 0,
            defaultCountryCode: $countryCode,
            defaultSender: \is_string($sender) && $sender !== '' ? $sender : null,
            httpClient: $this->api,
        );
    }

    public function client(): Client
    {
        return $this->fakeClient;
    }

    // ---------------------------------------------------------------- setup

    /** Balance returned by balance()->get() and used by estimates. */
    public function withBalance(int $balance): static
    {
        $this->api->balance = $balance;

        return $this;
    }

    /**
     * Approved Sender IDs. Once set, any other sender is refused
     * (SENDER_ID_NOT_APPROVED), like the API does.
     *
     * @param array<array-key, string> $senderIds
     */
    public function withSenderIds(array $senderIds): static
    {
        $this->api->senderIds = array_values($senderIds);

        return $this;
    }

    /** Code generated by the next OTP sends (random 6 digits by default). */
    public function withOtpCode(string $code): static
    {
        $this->api->otpCode = $code;

        return $this;
    }

    /** Attempts allowed per code (max_attempts, attempts_remaining). Default 3. */
    public function withOtpMaxAttempts(int $maxAttempts): static
    {
        $this->api->otpMaxAttempts = max(1, $maxAttempts);

        return $this;
    }

    /** Value returned as resendAfterSeconds (the fake never refuses a resend). Default 60. */
    public function withOtpResendAfter(int $seconds): static
    {
        $this->api->otpResendAfterSeconds = max(0, $seconds);

        return $this;
    }

    /**
     * The next API call fails with this error, e.g.
     * failNextRequest('INSUFFICIENT_CREDITS', 409, ['available' => 0, 'required' => 1]).
     *
     * @param array<mixed> $details
     */
    public function failNextRequest(string $code, int $status = 422, array $details = [], string $message = 'Erreur simulée.'): static
    {
        $this->api->failures[] = ['status' => $status, 'code' => $code, 'message' => $message, 'details' => $details];

        return $this;
    }

    // ------------------------------------------------------------- inspect

    /**
     * Every SMS sent (replays of an idempotent request are not counted).
     *
     * @return list<SentSms>
     */
    public function sent(?callable $callback = null): array
    {
        return $callback === null ? $this->api->sms : array_values(array_filter($this->api->sms, static fn (SentSms $sms): bool => (bool) $callback($sms)));
    }

    /**
     * @return list<SentOtp>
     */
    public function otps(?callable $callback = null): array
    {
        return $callback === null ? $this->api->otps : array_values(array_filter($this->api->otps, static fn (SentOtp $otp): bool => (bool) $callback($otp)));
    }

    /**
     * The last OTP code sent (to this number, if given): use it to fill the
     * verification form in a feature test.
     */
    public function otpCode(?string $phone = null): ?string
    {
        $normalized = $phone === null ? null : (PhoneNumber::normalize($phone, $this->countryCode) ?? $phone);
        $otps = $this->otps(static fn (SentOtp $otp): bool => $normalized === null || $otp->phone === $normalized);
        $last = end($otps);

        return $last === false ? null : $last->code;
    }

    // ----------------------------------------------------------- assertions

    /**
     * @param (callable(SentSms): bool)|null $callback
     */
    public function assertSmsSent(?callable $callback = null): void
    {
        PHPUnit::assertNotEmpty(
            $this->sent($callback),
            $callback === null ? 'No SMS was sent.' : 'No SMS matching the given callback was sent.',
        );
    }

    /**
     * @param (callable(SentSms): bool)|null $callback
     */
    public function assertSmsSentTo(string $phone, ?callable $callback = null): void
    {
        $matching = $this->sent(static fn (SentSms $sms): bool => $sms->hasRecipient($phone) && ($callback === null || $callback($sms)));

        PHPUnit::assertNotEmpty($matching, \sprintf('No SMS%s was sent to %s.', $callback === null ? '' : ' matching the callback', PhoneNumber::mask($phone)));
    }

    public function assertSmsNotSentTo(string $phone): void
    {
        PHPUnit::assertEmpty(
            $this->sent(static fn (SentSms $sms): bool => $sms->hasRecipient($phone)),
            \sprintf('An SMS was unexpectedly sent to %s.', PhoneNumber::mask($phone)),
        );
    }

    /** Number of send requests (one per send() / sendMany() / notification). */
    public function assertSmsSentCount(int $count): void
    {
        PHPUnit::assertCount($count, $this->api->sms, \sprintf('Expected %d SMS send(s), got %d.', $count, \count($this->api->sms)));
    }

    /** No SMS and no OTP were sent. */
    public function assertNothingSent(): void
    {
        PHPUnit::assertEmpty($this->api->sms, \sprintf('%d SMS send(s) were unexpectedly made.', \count($this->api->sms)));
        PHPUnit::assertEmpty($this->api->otps, \sprintf('%d OTP(s) were unexpectedly sent.', \count($this->api->otps)));
    }

    /**
     * @param string|(callable(SentOtp): bool)|null $phoneOrCallback a number (any format) or a callback
     */
    public function assertOtpSent(string|callable|null $phoneOrCallback = null): void
    {
        if (\is_string($phoneOrCallback)) {
            $normalized = PhoneNumber::normalize($phoneOrCallback, $this->countryCode) ?? $phoneOrCallback;
            PHPUnit::assertNotEmpty(
                $this->otps(static fn (SentOtp $otp): bool => $otp->phone === $normalized),
                \sprintf('No OTP was sent to %s.', PhoneNumber::mask($phoneOrCallback)),
            );

            return;
        }

        PHPUnit::assertNotEmpty($this->otps($phoneOrCallback), $phoneOrCallback === null ? 'No OTP was sent.' : 'No OTP matching the given callback was sent.');
    }

    public function assertNoOtpSent(): void
    {
        PHPUnit::assertEmpty($this->api->otps, \sprintf('%d OTP(s) were unexpectedly sent.', \count($this->api->otps)));
    }
}
