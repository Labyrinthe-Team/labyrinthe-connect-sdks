using System;
using System.Collections.Generic;
using System.Text;

namespace Labyrinthe.Connect;

/// <summary>An SMS, one per recipient.</summary>
/// <remarks>The text is deliberately not returned by the API (it may contain an OTP code).
/// <see cref="object.ToString"/> masks the recipient.</remarks>
public sealed record Message
{
    /// <summary>Message identifier (UUID).</summary>
    public string Id { get; init; } = string.Empty;

    /// <summary>Your reference, given at send time.</summary>
    public string? Reference { get; init; }

    /// <summary>International format without "+", e.g. <c>243812345678</c>. Personal data: mask it in your logs.</summary>
    public string Recipient { get; init; } = string.Empty;

    /// <summary>Sender shown on the handset.</summary>
    public string? Sender { get; init; }

    /// <summary>GSM-7 or UCS-2; <see langword="null"/> when the API does not tell.</summary>
    public SmsEncoding? Encoding { get; init; }

    /// <summary>Current status.</summary>
    public MessageStatus Status { get; init; }

    /// <summary>Number of SMS segments.</summary>
    public int Segments { get; init; }

    /// <summary>Credits charged (equal to <see cref="Segments"/>; fictitious with a test key).</summary>
    public int CreditsCharged { get; init; }

    /// <summary>Campaign of origin (messages sent from the client area).</summary>
    public string? CampaignId { get; init; }

    /// <summary>Identifier given by the SMS provider.</summary>
    public string? ProviderMessageId { get; init; }

    /// <summary>Error code of a failed message.</summary>
    public string? ErrorCode { get; init; }

    /// <summary>Error message of a failed message.</summary>
    public string? ErrorMessage { get; init; }

    /// <summary>Creation time.</summary>
    public DateTimeOffset? CreatedAt { get; init; }

    /// <summary>Hand-over to the provider.</summary>
    public DateTimeOffset? SubmittedAt { get; init; }

    /// <summary>Delivery receipt.</summary>
    public DateTimeOffset? DeliveredAt { get; init; }

    private bool PrintMembers(StringBuilder builder)
    {
        builder.Append("Id = ").Append(Id)
            .Append(", Reference = ").Append(Reference)
            .Append(", Recipient = ").Append(PhoneNumber.Mask(Recipient))
            .Append(", Status = ").Append(Status)
            .Append(", Segments = ").Append(Segments)
            .Append(", CreditsCharged = ").Append(CreditsCharged)
            .Append(", CreatedAt = ").Append(CreatedAt);
        return true;
    }
}

/// <summary>Result of <see cref="Resources.SmsResource.SendManyAsync"/>: one message per distinct recipient.</summary>
public sealed record MessageBatch
{
    /// <summary>The messages created (or replayed), one per distinct recipient.</summary>
    public IReadOnlyList<Message> Messages { get; init; } = Array.Empty<Message>();

    /// <summary>The <c>Idempotency-Key</c> used for this send (yours, or the one generated by the SDK).</summary>
    public string IdempotencyKey { get; init; } = string.Empty;

    /// <summary>True when the API replayed an earlier identical request: nothing was sent or billed again.</summary>
    public bool Replayed { get; init; }

    /// <inheritdoc cref="Balance.RequestId"/>
    public string? RequestId { get => response.RequestId; init => response = new ResponseMetadata(value); }

    private readonly ResponseMetadata response;
}

/// <summary>Cost of a send, computed by the API without sending anything.</summary>
public sealed record Estimate
{
    /// <inheritdoc cref="Balance.RequestId"/>
    public string? RequestId { get => response.RequestId; init => response = new ResponseMetadata(value); }

    private readonly ResponseMetadata response;

    /// <summary>GSM-7 or UCS-2.</summary>
    public SmsEncoding Encoding { get; init; }

    /// <summary>Number of characters of the body.</summary>
    public int Characters { get; init; }

    /// <summary>Segments of each message.</summary>
    public int SegmentsPerMessage { get; init; }

    /// <summary>Valid recipients only (invalid numbers are ignored, not rejected).</summary>
    public int RecipientsCount { get; init; }

    /// <summary>Credits needed for the whole send.</summary>
    public int TotalCredits { get; init; }

    /// <summary>Balance after the send (negative when insufficient); <see langword="null"/> if the account never had credits.</summary>
    public int? BalanceAfter { get; init; }

    /// <summary>True when the current balance covers the send.</summary>
    public bool IsAffordable => BalanceAfter is >= 0;
}

/// <summary>Credit balance, in SMS credits (1 credit = 1 segment).</summary>
public sealed record Balance
{
    /// <summary>Available credits.</summary>
    public int Available { get; init; }

    /// <summary>Credits held by running campaigns.</summary>
    public int Held { get; init; }

    /// <summary>Identifier of the API request that returned this result (<c>X-Request-Id</c>), for support; yours when
    /// you sent one (<see cref="LabyrintheClient.WithRequestId(string)"/>). Not part of the equality of results.</summary>
    public string? RequestId { get => response.RequestId; init => response = new ResponseMetadata(value); }

    private readonly ResponseMetadata response;
}

/// <summary>Métadonnées de réponse, neutres pour l'égalité des records (deux résultats identiques restent égaux quel que
/// soit l'identifiant de requête qui les a produits).</summary>
internal readonly struct ResponseMetadata : IEquatable<ResponseMetadata>
{
    public ResponseMetadata(string? requestId) => RequestId = requestId;

    public string? RequestId { get; }

    public bool Equals(ResponseMetadata other) => true;

    public override bool Equals(object? obj) => obj is ResponseMetadata;

    public override int GetHashCode() => 0;
}

/// <summary>An approved sender name, usable as <c>Sender</c> when sending.</summary>
public sealed record SenderId
{
    /// <summary>Identifier (UUID).</summary>
    public string Id { get; init; } = string.Empty;

    /// <summary>The name shown on the handset, e.g. <c>MYSHOP</c> (11 characters max).</summary>
    public string Value { get; init; } = string.Empty;

    /// <summary>Review status (<see cref="SenderIdStatus.Approved"/> for every listed Sender ID).</summary>
    public SenderIdStatus Status { get; init; }

    /// <summary>Declared use.</summary>
    public string? Purpose { get; init; }

    /// <summary>Why it was rejected.</summary>
    public string? RejectionReason { get; init; }

    /// <summary>True for the account's default Sender ID.</summary>
    public bool IsDefault { get; init; }

    /// <summary>Creation time.</summary>
    public DateTimeOffset? CreatedAt { get; init; }
}

/// <summary>A refused recipient of an all-or-nothing send.</summary>
public sealed record RejectedRecipient
{
    /// <summary>Number as received, or normalised. Personal data: <see cref="object.ToString"/> masks it.</summary>
    public string Recipient { get; init; } = string.Empty;

    /// <summary>Why it was refused.</summary>
    public RejectionReason Reason { get; init; }

    private bool PrintMembers(StringBuilder builder)
    {
        builder.Append("Recipient = ").Append(PhoneNumber.Mask(Recipient)).Append(", Reason = ").Append(Reason);
        return true;
    }
}

/// <summary>Result of an OTP send.</summary>
/// <remarks>Store <see cref="OtpId"/> server-side (session, cache…) and pass it to
/// <see cref="Resources.OtpResource.VerifyAsync(string, string, System.Threading.CancellationToken)"/> with the code
/// typed by the user. <see cref="TestCode"/> never appears in <see cref="object.ToString"/>.</remarks>
public sealed record OtpSendResult
{
    /// <summary>Identifier to pass to <c>VerifyAsync</c>.</summary>
    public string OtpId { get; init; } = string.Empty;

    /// <summary>When the code expires.</summary>
    public DateTimeOffset ExpiresAt { get; init; }

    /// <summary>Wrong attempts allowed before the code is blocked.</summary>
    public int MaxAttempts { get; init; }

    /// <summary>Number of characters of the code (4 to 8, from the account's OTP settings), e.g. to size the input field;
    /// 0 when an older API does not tell.</summary>
    public int CodeLength { get; init; }

    /// <summary>Alphabet of the code: <see cref="OtpCodeType.Numeric"/> (numeric keyboard) or <see cref="OtpCodeType.Alphanumeric"/>.</summary>
    public OtpCodeType CodeType { get; init; }

    /// <summary>Seconds before a new send to the same number is accepted while this code is not verified (countdown of a
    /// <i>Resend the code</i> button).</summary>
    public int ResendAfterSeconds { get; init; }

    /// <summary>The <c>Idempotency-Key</c> used for this send (yours, or the one generated by the SDK).</summary>
    public string IdempotencyKey { get; init; } = string.Empty;

    /// <summary>True when the API replayed an earlier identical request (same <see cref="IdempotencyKey"/>): same
    /// <see cref="OtpId"/>, no new SMS, nothing billed again.</summary>
    public bool Replayed { get; init; }

    /// <inheritdoc cref="Balance.RequestId"/>
    public string? RequestId { get => response.RequestId; init => response = new ResponseMetadata(value); }

    /// <summary>The code, ONLY with a test key (<c>lsk_test_…</c>); always <see langword="null"/> with a live key.</summary>
    /// <remarks>Nothing is sent by SMS in test mode, so the API returns the code to let you test the verification.
    /// Never log it, never show it to end users.</remarks>
    public string? TestCode { get; init; }

    private readonly ResponseMetadata response;

    private bool PrintMembers(StringBuilder builder)
    {
        builder.Append("OtpId = ").Append(OtpId)
            .Append(", ExpiresAt = ").Append(ExpiresAt)
            .Append(", MaxAttempts = ").Append(MaxAttempts)
            .Append(", CodeLength = ").Append(CodeLength)
            .Append(", CodeType = ").Append(CodeType)
            .Append(", ResendAfterSeconds = ").Append(ResendAfterSeconds)
            .Append(", Replayed = ").Append(Replayed ? "true" : "false")
            .Append(", RequestId = ").Append(RequestId)
            .Append(", TestCode = ").Append(TestCode is null ? "null" : "[redacted]");
        return true;
    }
}

/// <summary>Result of an OTP verification. A wrong code is not an exception.</summary>
public sealed record OtpVerifyResult
{
    /// <summary>True when the code is correct: log the user in.</summary>
    public bool Verified { get; init; }

    /// <summary>Why the verification failed; <see langword="null"/> when <see cref="Verified"/> is true.</summary>
    public OtpFailureReason? Reason { get; init; }

    /// <summary>Attempts still possible: a number after <see cref="OtpFailureReason.InvalidCode"/>, 0 with
    /// <see cref="OtpFailureReason.MaxAttemptsReached"/>, <see langword="null"/> when the code is verified, already used
    /// or expired (or with an older API).</summary>
    public int? AttemptsRemaining { get; init; }

    /// <inheritdoc cref="Balance.RequestId"/>
    public string? RequestId { get => response.RequestId; init => response = new ResponseMetadata(value); }

    private readonly ResponseMetadata response;
}
