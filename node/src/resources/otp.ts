import { InvalidArgumentError } from '../errors.js';
import { apiReader, characterCount, toOtpVerifyResult, type Json } from '../internal/data.js';
import { assertStripAccents, resolveIdempotencyKey } from '../internal/idempotency.js';
import type { Transport } from '../internal/transport.js';
import { PhoneNumber, toApiNumber } from '../phone.js';
import { OtpCodeType, type OtpLocale, type OtpVerifyResult, type RequestOptions } from '../types.js';

export const MAX_TEMPLATE_LENGTH = 1600;
export const MAX_CODE_LENGTH = 20;
export const MAX_WEB_OTP_DOMAIN_LENGTH = 253;
/** Host name accepted by `web_otp_domain` (components.schemas.SendOtpRequest, checked by the contract tests). */
export const WEB_OTP_DOMAIN_PATTERN =
  /^(?=.{1,253}$)([A-Za-z0-9]([A-Za-z0-9-]{0,61}[A-Za-z0-9])?\.)+[A-Za-z]([A-Za-z0-9-]{0,61}[A-Za-z0-9])?$/;

export interface SendOtpParams {
  /** Phone number, international or local format. */
  phone: string;
  /** Must contain "{code}"; optional "{app_name}", "{minutes}". Defaults to the account's OTP settings. */
  template?: string;
  /** Language of the standard template. Defaults to the account's OTP settings. */
  locale?: OtpLocale;
  /**
   * Web OTP API: host name of the site that reads the code (e.g. "app.example.com":
   * no scheme, port or path). The API adds the last line `@app.example.com #123456`
   * to the SMS, so that Chrome on Android offers to fill the code automatically.
   */
  webOtpDomain?: string;
  /** Replace accents and typographic characters with ASCII (GSM-7: often half the cost). Default false. */
  stripAccents?: boolean;
  /**
   * Max 255 characters. Generated (UUID v4) when absent, and reused by the
   * SDK's retries: a retried send never sends a second SMS. Pass your own to
   * also protect against your own retries for 24 hours (a replay returns the
   * same `otpId`, without a new SMS).
   */
  idempotencyKey?: string;
}

export interface VerifyOtpParams {
  /** The `otpId` returned by `otp.send()`, kept server-side. */
  otpId: string;
  /** The code typed by the user (spaces and case are ignored by the API). */
  code: string;
}

const INSPECT = Symbol.for('nodejs.util.inspect.custom');
const DENO_INSPECT = Symbol.for('Deno.customInspect');
const CODE_TYPES: readonly string[] = [OtpCodeType.Numeric, OtpCodeType.Alphanumeric];

/** @internal */
export interface OtpSendResultInit {
  otpId: string;
  expiresAt: Date;
  maxAttempts: number;
  codeLength: number | null;
  codeType: OtpCodeType | null;
  resendAfterSeconds: number | null;
  testCode: string | null;
  idempotencyKey: string;
  replayed: boolean;
  requestId: string | null;
}

/**
 * Result of an OTP send. Store `otpId` server-side (session, cache…) and pass
 * it to `otp.verify()` with the code typed by the user.
 */
export class OtpSendResult {
  readonly otpId: string;
  readonly expiresAt: Date;
  readonly maxAttempts: number;
  /** Number of characters of the code (4 to 8, account's OTP settings); null only with an API older than 1.2.0. */
  readonly codeLength: number | null;
  /** `numeric` (0-9) or `alphanumeric` (case-insensitive); null only with an API older than 1.2.0. */
  readonly codeType: OtpCodeType | null;
  /**
   * Seconds before a new send to this number is accepted while this code is
   * not verified: show a "Resend the code" countdown. Null only with an API older than 1.2.0.
   */
  readonly resendAfterSeconds: number | null;
  /** The Idempotency-Key of this send (yours, or the one generated by the SDK). */
  readonly idempotencyKey: string;
  /** True when the API replayed an earlier send with the same Idempotency-Key: no new SMS, no new charge. */
  readonly replayed: boolean;
  /** `X-Request-Id` of the response, for the support; null when absent. */
  readonly requestId: string | null;
  readonly #testCode: string | null;

  /** @internal */
  constructor(init: OtpSendResultInit) {
    this.otpId = init.otpId;
    this.expiresAt = init.expiresAt;
    this.maxAttempts = init.maxAttempts;
    this.codeLength = init.codeLength;
    this.codeType = init.codeType;
    this.resendAfterSeconds = init.resendAfterSeconds;
    this.idempotencyKey = init.idempotencyKey;
    this.replayed = init.replayed;
    this.requestId = init.requestId;
    this.#testCode = init.testCode;
  }

  /**
   * The code, ONLY with a test key (`lsk_test_…`): nothing is sent by SMS in
   * test mode, so the API returns the code to let you test `verify()`. Always
   * null with a live key. Never log it, never show it to end users. Hidden
   * from `JSON.stringify()` and `console.log()`.
   */
  get testCode(): string | null {
    return this.#testCode;
  }

  toJSON(): {
    otpId: string;
    expiresAt: string;
    maxAttempts: number;
    codeLength: number | null;
    codeType: OtpCodeType | null;
    resendAfterSeconds: number | null;
    replayed: boolean;
    requestId: string | null;
  } {
    return {
      otpId: this.otpId,
      expiresAt: this.expiresAt.toISOString(),
      maxAttempts: this.maxAttempts,
      codeLength: this.codeLength,
      codeType: this.codeType,
      resendAfterSeconds: this.resendAfterSeconds,
      replayed: this.replayed,
      requestId: this.requestId,
    };
  }

  [INSPECT](): Record<string, unknown> {
    return this.#redacted();
  }

  [DENO_INSPECT](): string {
    return `OtpSendResult ${JSON.stringify(this.#redacted())}`;
  }

  #redacted(): Record<string, unknown> {
    return {
      ...this.toJSON(),
      expiresAt: this.expiresAt,
      testCode: this.#testCode === null ? null : '[redacted]',
    };
  }
}

/**
 * One-time passwords by SMS (`client.otp`).
 *
 * 1. `send({ phone })` and keep `otpId` server-side (session);
 * 2. the user types the code received by SMS (`codeLength`, `codeType`);
 * 3. `verify({ otpId, code })`: log the user in when `verified` is true.
 *
 * Code length, alphabet, validity, attempts, anti-resend delay, sender and
 * template come from the account's OTP settings (client area > OTP verification).
 */
export class Otp {
  readonly #transport: Transport;
  readonly #defaultCountryCode: string;

  /** @internal */
  constructor(transport: Transport, defaultCountryCode: string) {
    this.#transport = transport;
    this.#defaultCountryCode = defaultCountryCode;
  }

  /**
   * Generates a code and sends it by SMS (billed like any SMS). A new send to
   * the same number invalidates the previous code.
   *
   * An Idempotency-Key is always sent (generated when you give none), so the
   * SDK retries network errors, 5xx, 429 TOO_MANY_REQUESTS and 409
   * IDEMPOTENCY_REQUEST_IN_PROGRESS with the same key: a retry never sends a
   * second SMS. The business limits (OTP_RESEND_TOO_SOON, OTP_RATE_LIMITED)
   * are never retried.
   */
  async send(params: SendOtpParams, options: RequestOptions = {}): Promise<OtpSendResult> {
    const body: Json = {
      phone: toApiNumber(PhoneNumber.normalizeOrThrow(params.phone, this.#defaultCountryCode, 'phone')),
    };
    // Valeurs non typées : l'appelant peut venir de JavaScript.
    const template: unknown = params.template;
    const locale: unknown = params.locale;
    const webOtpDomain: unknown = params.webOtpDomain;
    const stripAccents: unknown = params.stripAccents;
    if (template !== undefined) {
      if (typeof template !== 'string' || !template.includes('{code}')) {
        throw new InvalidArgumentError('The OTP template must contain the {code} token.');
      }
      if (characterCount(template) > MAX_TEMPLATE_LENGTH) {
        throw new InvalidArgumentError(`The OTP template must be at most ${String(MAX_TEMPLATE_LENGTH)} characters.`);
      }
      body['template'] = template;
    }
    if (locale !== undefined) {
      if (locale !== 'fr' && locale !== 'en') {
        throw new InvalidArgumentError('locale must be "fr" or "en".');
      }
      body['locale'] = locale;
    }
    if (webOtpDomain !== undefined) {
      if (typeof webOtpDomain !== 'string' || !WEB_OTP_DOMAIN_PATTERN.test(webOtpDomain)) {
        throw new InvalidArgumentError(
          'webOtpDomain must be a host name with at least two labels, without scheme, port or path (e.g. "app.example.com").',
        );
      }
      body['web_otp_domain'] = webOtpDomain.toLowerCase();
    }
    assertStripAccents(stripAccents);
    if (stripAccents !== undefined) {
      body['strip_accents'] = stripAccents;
    }
    const idempotencyKey = await resolveIdempotencyKey(params.idempotencyKey);

    const response = await this.#transport.request('POST', '/otp/send', 'safe', {
      body,
      ...options,
      headers: { 'Idempotency-Key': idempotencyKey },
    });
    const data = apiReader.object(response.body, 'data');
    const codeType = apiReader.nullableString(data, 'code_type');
    return new OtpSendResult({
      otpId: apiReader.string(data, 'otp_id'),
      expiresAt: apiReader.date(data, 'expires_at'),
      maxAttempts: apiReader.int(data, 'max_attempts'),
      // Champs de la spec 1.2.0 : null avec un backend plus ancien (l'envoi a réussi, on ne le fait pas échouer).
      codeLength: apiReader.nullableInt(data, 'code_length'),
      codeType: codeType === null ? null : ((CODE_TYPES.includes(codeType) ? codeType : 'unknown') as OtpCodeType),
      resendAfterSeconds: apiReader.nullableInt(data, 'resend_after_seconds'),
      testCode: apiReader.nullableString(data, 'test_code'),
      idempotencyKey,
      replayed: response.headers['idempotent-replayed'] === 'true',
      requestId: response.headers['x-request-id'] ?? null,
    });
  }

  /**
   * Checks a code. A wrong code is NOT an error: the result says
   * `verified: false` with a `reason` and `attemptsRemaining`, and one attempt
   * is consumed. Free. Throws `NotFoundError` for an unknown `otpId` (or one
   * from another account).
   *
   * Retried only on 429 TOO_MANY_REQUESTS (refused before processing): after a
   * network error or a 5xx, an attempt may have been consumed.
   */
  async verify(params: VerifyOtpParams, options: RequestOptions = {}): Promise<OtpVerifyResult> {
    const { otpId, code } = params;
    if (typeof otpId !== 'string' || otpId.trim() === '') {
      throw new InvalidArgumentError('otpId cannot be empty.');
    }
    if (typeof code !== 'string' || code.trim() === '' || code.length > MAX_CODE_LENGTH) {
      throw new InvalidArgumentError(`The code must be 1 to ${String(MAX_CODE_LENGTH)} characters.`);
    }

    const response = await this.#transport.request('POST', '/otp/verify', 'throttled-only', {
      body: { otp_id: otpId, code },
      ...options,
    });
    return toOtpVerifyResult(apiReader.object(response.body, 'data'));
  }

  toJSON(): Record<string, unknown> {
    return { transport: this.#transport.toJSON(), defaultCountryCode: this.#defaultCountryCode };
  }

  [INSPECT](): Record<string, unknown> {
    return this.toJSON();
  }
}
