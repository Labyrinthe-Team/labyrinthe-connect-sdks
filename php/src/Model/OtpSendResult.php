<?php

declare(strict_types=1);

namespace Labyrinthe\Connect\Model;

use Labyrinthe\Connect\Enum\OtpCodeType;
use Labyrinthe\Connect\Internal\Data;

/**
 * Result of an OTP send. Store `otpId` server-side (session, cache…) and pass
 * it to verify() with the code typed by the user. Never send it to a place
 * you do not control: it is not secret, but it identifies the attempt.
 *
 * `codeLength` and `codeType` describe the code to type (size and keyboard of
 * the input), `resendAfterSeconds` the countdown before "Resend the code".
 */
final class OtpSendResult implements \JsonSerializable
{
    public function __construct(
        public readonly string $otpId,
        public readonly \DateTimeImmutable $expiresAt,
        public readonly int $maxAttempts,
        #[\SensitiveParameter]
        private readonly ?string $testCode = null,
        /** Number of characters of the code (4 to 8). */
        public readonly int $codeLength = 0,
        public readonly OtpCodeType $codeType = OtpCodeType::Unknown,
        /** Seconds before a new send to the same number is accepted while this code is not verified. */
        public readonly int $resendAfterSeconds = 0,
        /** True when the API replayed an earlier send with the same Idempotency-Key (no new SMS, same otpId). */
        public readonly bool $replayed = false,
        /** The Idempotency-Key used for this send (yours, or the one generated by the SDK). */
        public readonly ?string $idempotencyKey = null,
    ) {
    }

    /**
     * @internal
     *
     * @param array<mixed> $data
     */
    public static function fromArray(array $data, bool $replayed = false, ?string $idempotencyKey = null): self
    {
        return new self(
            otpId: Data::string($data, 'otp_id'),
            expiresAt: Data::dateTime($data, 'expires_at'),
            maxAttempts: Data::int($data, 'max_attempts'),
            testCode: Data::nullableString($data, 'test_code'),
            codeLength: Data::int($data, 'code_length'),
            codeType: OtpCodeType::fromApi(Data::string($data, 'code_type')),
            resendAfterSeconds: Data::int($data, 'resend_after_seconds'),
            replayed: $replayed,
            idempotencyKey: $idempotencyKey,
        );
    }

    /**
     * The code, ONLY with a test key (lsk_test_…): nothing is sent by SMS in
     * test mode, so the API returns the code to let you test verify(). Always
     * null with a live key. Never log it, never show it to end users.
     */
    public function testCode(): ?string
    {
        return $this->testCode;
    }

    /** When "Resend the code" can be offered: $now + resendAfterSeconds. */
    public function resendAvailableAt(?\DateTimeImmutable $now = null): \DateTimeImmutable
    {
        return ($now ?? new \DateTimeImmutable())->add(new \DateInterval('PT'.max(0, $this->resendAfterSeconds).'S'));
    }

    /**
     * The test code is never serialised.
     *
     * @return array{otp_id: string, expires_at: string, max_attempts: int, code_length: int, code_type: string, resend_after_seconds: int}
     */
    public function jsonSerialize(): array
    {
        return [
            'otp_id' => $this->otpId,
            'expires_at' => $this->expiresAt->format(\DATE_ATOM),
            'max_attempts' => $this->maxAttempts,
            'code_length' => $this->codeLength,
            'code_type' => $this->codeType->value,
            'resend_after_seconds' => $this->resendAfterSeconds,
        ];
    }

    /**
     * @return array<string, mixed>
     */
    public function __debugInfo(): array
    {
        return [
            'otpId' => $this->otpId,
            'expiresAt' => $this->expiresAt,
            'maxAttempts' => $this->maxAttempts,
            'codeLength' => $this->codeLength,
            'codeType' => $this->codeType,
            'resendAfterSeconds' => $this->resendAfterSeconds,
            'replayed' => $this->replayed,
            'idempotencyKey' => $this->idempotencyKey,
            'testCode' => $this->testCode === null ? null : '[redacted]',
        ];
    }
}
