<?php

declare(strict_types=1);

namespace Labyrinthe\Connect\Http;

/**
 * Low-level metadata of the last HTTP response received by a client (success
 * or error): status, headers, request id. See Client::lastResponse().
 *
 *     $client->sms->send('0812345678', 'Hello');
 *     $requestId = $client->lastResponse()?->requestId();
 */
final class ResponseInfo
{
    /**
     * @param array<string, string> $headers lower-case names
     */
    public function __construct(
        public readonly int $status,
        public readonly array $headers,
    ) {
    }

    /** A response header (case-insensitive name). */
    public function header(string $name): ?string
    {
        return $this->headers[strtolower($name)] ?? null;
    }

    /** Request identifier (X-Request-Id): yours when valid, otherwise generated by the API. Give it to support. */
    public function requestId(): ?string
    {
        return $this->header('x-request-id');
    }

    /** Major API version that served the response (X-Api-Version, e.g. "1"). */
    public function apiVersion(): ?string
    {
        return $this->header('x-api-version');
    }

    /** True when the API replayed an earlier request with the same Idempotency-Key (Idempotent-Replayed). */
    public function isReplayed(): bool
    {
        return $this->header('idempotent-replayed') === 'true';
    }

    /** Requests allowed per minute (X-RateLimit-Limit), on successful responses. */
    public function rateLimitLimit(): ?int
    {
        return self::int($this->header('x-ratelimit-limit'));
    }

    /** Requests left in the current minute (X-RateLimit-Remaining), on successful responses. */
    public function rateLimitRemaining(): ?int
    {
        return self::int($this->header('x-ratelimit-remaining'));
    }

    private static function int(?string $value): ?int
    {
        return $value !== null && preg_match('/^\d+$/', trim($value)) === 1 ? (int) trim($value) : null;
    }
}
